def _build():
    """Expand ``TRANSLATIONS`` into the ``{(context, msgid): text}`` form Blender wants.

    Blender resolves a locale by trying the full identifier first, then the bare
    language code, so each entry is aliased under both its language prefix and the
    capitalisation the OS uses. That covers regional variants and the "Automatic"
    language setting, which reports the system locale (e.g. ``zh_Hant``) instead
    of a menu identifier.
    """
    dictionary = {}
    for lang, messages in TRANSLATIONS.items():
        entries = {
            (ctxt, msgid): text
            for msgid, text in messages.items()
            for ctxt in CONTEXTS[msgid]
        }
        language, _, region = lang.partition("_")
        for alias in (lang, f"{language}_{region.capitalize()}", language):
            dictionary.setdefault(alias, entries)
    return dictionary


